use std::{fs, path::Path};
use ts_rs::TS;
use ytm_protocol::*;

fn main() {
    let declarations = [
        TrackInfo::decl(),
        PlaybackState::decl(),
        AudioStatus::decl(),
        AccountStatus::decl(),
        PlayerCommand::decl(),
        PlayerEvent::decl(),
        Role::decl(),
        SyncStatus::decl(),
        Member::decl(),
        SyncFrame::decl(),
        PartyMsg::decl(),
        CatalogKind::decl(),
        CatalogRequest::decl(),
        MusicItem::decl(),
        CatalogPage::decl(),
        CatalogReply::decl(),
    ];
    let output = format!(
        "// Generated by cargo run -p ytm-protocol --bin export-types. Do not edit.\n{}\n",
        declarations
            .iter()
            .map(|d| format!("export {d}"))
            .collect::<Vec<_>>()
            .join("\n")
    );
    let path =
        Path::new(env!("CARGO_MANIFEST_DIR")).join("../../packages/protocol/src/generated.ts");
    fs::write(path, output).expect("write TypeScript protocol");
}
